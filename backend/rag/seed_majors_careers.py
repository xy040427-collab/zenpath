from rag.chunker import chunk_document
from rag.pipeline import index_chunks_sync


def generate_major_profiles():
    """Generate major profile chunks."""
    chunks = []
    for category_name, profile_text in MAJOR_CATEGORY_PROFILES.items():
        major_chunks = chunk_document(
            text=profile_text,
            doc_type="major_profile",
            school_name=None,  # Generic, not school-specific
            major_name=category_name,
            year=2025,
            source_url=None,
            source_name="择境专业知识库（人工整理）",
            source_type="manual",
            data_source="manual",
            confidence="medium",
        )
        chunks.extend(major_chunks)
    return chunks


def generate_career_paths():
    """Generate career path chunks."""
    chunks = []
    for category, paths in CAREER_PATHS.items():
        for path in paths:
            career_chunks = chunk_document(
                text=path["content"],
                doc_type="career_path",
                school_name=None,
                major_name=category,
                year=2025,
                source_url=None,
                source_name="择境职业路径资料库（人工整理）",
                source_type="manual",
                data_source="manual",
                confidence="medium",
            )
            chunks.extend(career_chunks)
    return chunks


