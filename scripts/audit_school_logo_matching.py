def normalize_name(raw: str) -> str:
    if not raw:
        return ''
    result = raw.strip()
    result = re.sub(r'\s+', ' ', result)
    result = re.sub(r'[\u200b-\u200d\ufeff]', '', result)
    result = result.replace('（', '(').replace('）', ')')
    return result


def clean_name(raw: str) -> str:
    result = normalize_name(raw)
    for pat in NOISE_PARENTHETICALS:
        result = pat.sub('', result)
    for pat in NOISE_TRAILING:
        result = pat.sub('', result)
    result = re.sub(r'\s+', ' ', result).strip()
    return result


def is_independent(name: str) -> bool:
    for pat in INDEPENDENT_COLLEGE_PATTERNS:
        if pat.search(name):
            return True
    return False


def find_longest_prefix(name: str) -> str | None:
    for canonical in CANONICAL_SORTED:
        if name.startswith(canonical):
            return canonical
    return None


def has_safe_suffix(name: str, prefix: str) -> bool:
    remainder = name[len(prefix):]
    if not remainder:
        return False
    clean_rem = remainder
    # Strip wrapping parens from remainder
    if clean_rem.startswith('(') and clean_rem.endswith(')'):
        clean_rem = clean_rem[1:-1]
    for suffix in SAFE_SUFFIXES:
        if remainder == suffix or clean_rem == suffix:
            return True
    return False


def resolve(raw_name: str) -> dict:
    warnings = []
    norm = normalize_name(raw_name)
    cleaned = clean_name(raw_name)

    logo_set = CANONICAL_SET
    for name, match_type in [
        (raw_name, 'exact'),
        (norm, 'normalized_exact'),
        (cleaned, 'cleaned_exact'),
    ]:
        if name in logo_set:
            return dict(originalName=raw_name, displayName=raw_name,
                        normalizedName=norm, logoName=name,
                        logoMatchType=match_type, confidence='high',
                        warnings=warnings)

    # Step 4: canonical prefix
    for candidate in [cleaned, norm, raw_name]:
        if is_independent(candidate):
            warnings.append(f'Risk blocked: "{candidate}" is independent college')
            break
        prefix = find_longest_prefix(candidate)
        if prefix and prefix in logo_set:
            if has_safe_suffix(candidate, prefix):
                return dict(originalName=raw_name, displayName=raw_name,
                            normalizedName=norm, logoName=prefix,
                            logoMatchType='canonical_prefix', confidence='high',
                            warnings=warnings)
            warnings.append(f'Prefix "{prefix}" found but suffix not safe')

    # Step 5: parent by suffix rule
    for candidate in [cleaned, norm]:
        if is_independent(candidate):
            warnings.append(f'Risk blocked: "{candidate}" is independent college')
            break
        stripped = re.sub(r'[（(][^）)]*[）)]', '', candidate).strip()
        if stripped != candidate and stripped in logo_set:
            return dict(originalName=raw_name, displayName=raw_name,
                        normalizedName=norm, logoName=stripped,
                        logoMatchType='parent_by_suffix_rule', confidence='high',
                        warnings=warnings)
        # Try removing trailing parenthesized content only
        after = re.sub(r'[（(][^）)]*[）)]$', '', candidate).strip()
        if after != candidate and after in logo_set:
            return dict(originalName=raw_name, displayName=raw_name,
                        normalizedName=norm, logoName=after,
                        logoMatchType='parent_by_suffix_rule', confidence='high',
                        warnings=warnings)

    # Step 6: fallback
    warnings.append(f'No logo matched for "{raw_name}"')
    return dict(originalName=raw_name, displayName=raw_name,
                normalizedName=norm, logoName=None,
                logoMatchType='fallback', confidence='low',
                warnings=warnings)


# ═══════════════════════════════════════════════
#  Collect all school names from data sources
# ═══════════════════════════════════════════════

def collect_school_names():
    db = sqlite3.connect(str(DB_PATH))
    all_names = set()

    # Jiangsu group trends
    for r in db.execute('SELECT DISTINCT school_name FROM jiangsu_group_trends WHERE school_name IS NOT NULL AND school_name != ""'):
        all_names.add(r[0])

    # admission_lines (sample — too many, take top by frequency)
    for r in db.execute('SELECT DISTINCT university_name FROM admission_lines WHERE university_name IS NOT NULL AND university_name != ""'):
        all_names.add(r[0])

    db.close()
    return sorted(all_names)


