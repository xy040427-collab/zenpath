def load_canonical_names():
    """Load from canonical_school_names.json (generated by the same script)."""
    if CANONICAL_PATH.exists():
        with open(CANONICAL_PATH) as f:
            return json.load(f)

    # Fallback: build from sources
    names = set()
    # URONDA_LOGO_MAP
    with open(LOGO_MAP_PATH) as f:
        content = f.read()
    for m in re.findall(r"'([^']+)':", content):
        names.add(m)
    # DB schools table
    db = sqlite3.connect(str(DB_PATH))
    for r in db.execute('SELECT name FROM schools'):
        if r[0]:
            names.add(r[0])
    db.close()
    return sorted(names)


